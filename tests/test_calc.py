"""Вычисления без ИИ: проценты, арифметика, единицы, валюты (курс подменяется — интернет не нужен)."""

import pytest

from core import calc, daily

I = calc.INFO


@pytest.mark.parametrize("phrase,answer", [
    # проценты
    ("сколько будет 15 процентов от 3200", "15 процентов от 3200 — это 480"),
    ("15% от 3200", "15 процентов от 3200 — это 480"),
    ("пятнадцать процентов от трёх тысяч двухсот", "15 процентов от 3200 — это 480"),
    ("21 процент от 300", "21 процент от 300 — это 63"),
    ("3200 плюс 15 процентов", "3200 плюс 15 процентов — это 3680"),
    ("сколько процентов составляет 480 от 3200", "480 от 3200 — это 15 процентов"),
    # арифметика
    ("2 плюс 2 умножить на 3", "8"),
    ("сколько будет семь умножить на восемь", "56"),
    ("100 / 7", "14,29"),
    ("корень из 144", "12"),
    ("5 в квадрате", "25"),
    ("2 в степени 10", "1024"),
    ("2 миллиона умножить на три тысячи", "6000000000"),
    ("2 тысячи триста плюс 1", "2301"),
    # единицы
    ("5 миль в километрах", "5 миль — это 8,05 километра"),
    ("переведи 5 миль в километры", "5 миль — это 8,05 километра"),
    ("сколько сантиметров в дюйме", "1 дюйм — это 2,54 сантиметра"),
    ("сколько километров в 5 милях", "5 миль — это 8,05 километра"),
    ("сколько секунд в сутках", "1 день — это 86400 секунд"),
    ("100 фаренгейт в цельсии", "100 градусов Фаренгейта — это 37,78 градуса Цельсия"),
    ("1 гигабайт в мегабайтах", "1 гигабайт — это 1024 мегабайта"),
    ("сколько соток в гектаре", "1 гектар — это 100 соток"),
    ("2,5 литра в галлонах", "2,5 литра — это 0,66 галлона"),
])
def test_calculate(phrase, answer):
    assert calc.calculate(phrase) == I + answer


def test_divide_by_zero():
    assert calc.calculate("10 разделить на 0").startswith(calc.FAIL)


@pytest.mark.parametrize("phrase,answer", [
    ("доллар к тенге", "1 доллар — это 500 тенге"),
    ("5 долларов в тенге", "5 долларов — это 2500 тенге"),
    ("доллар, в тенге", "1 доллар — это 500 тенге"),
    ("100 тенге в рублях", "100 тенге — это 16 рублей"),
    ("1000 тенге в долларах", "1000 тенге — это 2 доллара"),
])
def test_currency(monkeypatch, phrase, answer):
    monkeypatch.setattr(daily, "_rates", lambda: {"USD": 1, "KZT": 500, "RUB": 80})
    assert calc.calculate(phrase) == I + answer


@pytest.mark.parametrize("phrase", [
    "сколько времени", "сколько градусов", "привет как дела", "открой телеграм",
    "переведи на английский", "минус", "курс доллара", "5 метров в килограммах",
])
def test_not_a_calculation(phrase):
    assert calc.parse(phrase) is None
